/* Shared facts + compatibility alias, without browser/network/user state. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const mounts = [{ innerHTML: '' }];
const context = vm.createContext({ window: {}, document: { querySelectorAll: () => mounts } }, { codeGeneration: { strings: false, wasm: false } });
vm.runInContext(read('platform/static/runtime-help.js'), context);
const html = context.window.RuntimeHelp.html();
assert(Object.isFrozen(context.window.RuntimeHelp));
assert.equal(mounts[0].innerHTML, html);
assert(html.startsWith('<details') && !/<details[^>]*\bopen\b/.test(html));
assert(html.includes('сервере') && html.includes('один запуск') && html.includes('не переходят в следующий запуск'));
assert(html.includes('текст кода') && html.includes('учебной папке') && html.includes('не скачивает интерпретатор'));
assert(!html.includes('<script') && !html.includes('onclick=') && !html.includes('<iframe'));
const calls = [];
const client = Object.freeze(Object.fromEntries(['run', 'runInteractive', 'cancelInteractive', 'warmup', 'ready'].map(name =>
  [name, function (...args) { calls.push({ name, args, self: this }); return name; }])));
context.window.PythonExecutionClient = client;
vm.runInContext(read('platform/static/runner.js'), context);
assert.equal(context.window.PyRunner, client, 'Keep the exact object and API, not an altered wrapper');
const status = () => {}, test = () => {}, signal = {};
assert.equal(context.window.PyRunner.run('print(1)', status, 'assert ok', test, signal), 'run');
assert.deepEqual(calls[0].args, ['print(1)', status, 'assert ok', test, signal]);
assert.equal(calls[0].self, client);
for (const name of ['runInteractive', 'cancelInteractive', 'warmup', 'ready']) context.window.PyRunner[name]();
assert.equal(calls.length, 5);
const app = read('platform/static/app.js');
const escStart = app.indexOf('const esc = '), escEnd = app.indexOf('\n  /* Условия', escStart);
const start = app.indexOf('function terminalEditorHtml('), end = app.indexOf('\n  let solved = ', start);
assert(escStart > 0 && escEnd > escStart && start > 0 && end > start);
vm.runInContext(app.slice(escStart, escEnd) + '\n' + app.slice(start, end) + '\nwindow.editorHtml = terminalEditorHtml;', context);
assert(context.window.editorHtml('main.py', '<textarea></textarea>', { resetId: 'reset' }).includes('runtime-help'));
assert(!context.window.editorHtml('вывод', '<pre>1</pre>').includes('runtime-help'), 'Do not duplicate guidance under output');
delete context.window.RuntimeHelp;
assert(!context.window.editorHtml('main.py', '<textarea></textarea>', { resetId: 'reset' }).includes('runtime-help'), 'Missing new asset keeps the old editor usable');
console.log('PASS: collapsed shared facts, static mount, exact PyRunner API/arguments, real editor integration, output and cached-asset fallback');
