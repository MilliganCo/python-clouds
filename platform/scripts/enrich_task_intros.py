def load_tasks() -> list[dict]:
    # A new topic can receive intros before the first full course build.
    # Preserve displayType and other author metadata instead of projecting it away.
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from build_tasks import parse
    return [{**task, "topicTitle": topic["title"]}
            for topic in parse() for task in topic['tasks']]


def load_existing_intros() -> dict:
    src = OUT.read_text(encoding="utf-8")
    # Вырезаем объект после =
    m = re.search(r"window\.TASK_INTRO\s*=\s*(\{[\s\S]*\});?\s*$", src.strip())
    if not m:
        raise SystemExit("не найден window.TASK_INTRO")
    # Используем node для безопасного парса JS-объекта
    raw = subprocess.check_output(
        [
            "node",
            "-e",
            "const fs=require('fs');const vm=require('vm');"
            "const c={window:{}};vm.createContext(c);"
            "vm.runInContext(fs.readFileSync(process.argv[1],'utf8'),c);"
            "process.stdout.write(JSON.stringify(c.window.TASK_INTRO));",
            str(OUT.resolve()),
        ],
        cwd=str(ROOT),
        text=True,
        encoding="utf-8",
    )
    return json.loads(raw)


def is_bootstrap(intro: dict | None) -> bool:
    if not intro:
        return True
    if intro.get("source") == "template":
        return True
    blob = json.dumps(intro, ensure_ascii=False)
    return any(m in blob for m in (*BOOTSTRAP_MARKERS, *TYPE_EXPLANATION_TAIL.values()))


def concepts_for(task: dict) -> list[str]:
    raw = task.get("concepts") or []
    cleaned = []
    for c in raw:
        s = str(c).strip()
        if not s or len(s) > 40:
            continue
        # не тащим куски ответа в concepts
        if re.fullmatch(r"[-+]?\d+(\.\d+)?", s):
            continue
        cleaned.append(s)
    if cleaned:
        return cleaned[:4]
    # из title — короткие токены в backticks
    title = task.get("title") or ""
    ticks = re.findall(r"`([^`]+)`", title)
    out = []
    for t in ticks:
        t = t.strip()
        if 1 < len(t) <= 24 and t not in out:
            out.append(t)
    return out[:4] or ["Python"]


def safe_title_phrase(title: str) -> str:
    """Название этапа для цели — раскавычиваем backticks, а не вырезаем их.

    Раньше вырезали содержимое backticks целиком (боялись «показать ответ»),
    но title — это уже curated короткое имя этапа (например, `append` и
    `insert`, Функция `reverse`), а не решение задания: те же термины
    concepts_for() и так показывает чипами. Вырезание оставляло на месте
    двух backtick-фрагментов только соединительное слово («и» и т.п.) —
    goal получался бессмысленным (найдено и исправлено 2026-07-21).
    """
    t = re.sub(r"`([^`]+)`", r"\1", title)
    t = re.sub(r"\s+", " ", t).strip(" —–-:.")
    return t or "этот этап"


