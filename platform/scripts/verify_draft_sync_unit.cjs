const assert=require('node:assert/strict');
const m=require('../static/draft-sync.js');
const r=(version,code,id='a'.repeat(32),starter='# starter')=>({scope:'sandbox',version,code,mutation_id:version?id:null,starter:version?starter:null});
const base=r(1,'base'),empty=r(0,null),remote=r(2,'other','b'.repeat(32));
const d=opts=>m.decide({base,remote:base,code:'base',starter:'# starter',dirty:false,pending:null,...opts});
assert.equal(d({}),'same');
assert.equal(d({remote,dirty:false}),'load');
assert.equal(d({remote,code:'local',dirty:true}),'conflict');
assert.equal(d({code:'local',dirty:true}),'save');
assert.equal(d({base:null,remote:empty,code:'local',dirty:true}),'save');
assert.equal(d({base:null,remote,code:'local',dirty:true}),'conflict');
assert.equal(d({remote:r(2,'base','b'.repeat(32),'old starter')}),'template');
assert.equal(d({remote:r(0,null)}),'conflict');
assert.equal(d({remote:r(1,'base','c'.repeat(32))}),'conflict');
assert.equal(d({remote:r(2,'', 'b'.repeat(32)),code:null,dirty:true}),'conflict','empty string is not reset');
const pending={mutation_id:'b'.repeat(32),base_version:1,base_mutation_id:base.mutation_id,code:'sent',starter:'# starter'};
assert.equal(d({remote:r(2,'sent','b'.repeat(32)),pending,code:'newer',dirty:true}),'ack');
assert.equal(d({pending,code:'newer',dirty:true}),'save','lost acknowledgement retries same pending mutation');
assert.equal(d({remote,pending,code:'newer',dirty:true}),'conflict');
assert.equal(m.validRecord(empty,'sandbox'),true);
assert.equal(m.validRecord({...base,version:NaN},'sandbox'),false);
assert.equal(m.validRecord({...base,scope:'task:2.9'},'sandbox'),false);
console.log('PASS draft sync model: clean versus dirty, no-base import, template/rewind/branch conflict, empty/reset, pending acknowledgement and newer local edit');
assert.match(m.syncLabel('ready',empty),/исходный|шаблон|писать/i);
assert.doesNotMatch(m.syncLabel('ready',empty),/сохранен[аоы]?/i);
assert.match(m.syncLabel('ready',base),/сохранено/i);
assert.match(m.syncLabel('ready',r(2,null)),/сброс/i);
for(const state of ['pending','offline','conflict','blocked','saving'])assert.doesNotMatch(m.syncLabel(state,base),/^Изменения сохранены/);
assert.match(m.syncLabel('ready',null),/загружаем/i);
console.log('PASS truthful sync labels: untouched starter, confirmed code/reset, pending/offline/conflict and initial connection');
