// Authored articles stay unchanged. This derives only the small routing/lead index.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
function buildTheoryManifest(staticDir){
 const html=fs.readFileSync(path.join(staticDir,'index.html'),'utf8');
 const names=[...html.matchAll(/data-course-src="(theory-articles-\d+(?:-\d+)?\.js)"/g)].map(match=>match[1]);
 if(!names.length||new Set(names).size!==names.length)throw new Error('Theory article declarations are missing or duplicated');
 const articles={};
 for(const file of names){
  const context=vm.createContext({window:{}});
  new vm.Script(fs.readFileSync(path.join(staticDir,file),'utf8'),{filename:file}).runInContext(context,{timeout:1000});
  const group=context.window.THEORY_ARTICLES;
  if(!group||typeof group!=='object'||Array.isArray(group)||!Object.keys(group).length)throw new Error('Empty theory group: '+file);
  for(const [id,article] of Object.entries(group)){
   if(!/^\d+$/.test(id)||Object.hasOwn(articles,id)||!article||typeof article.lead!=='string'||!Array.isArray(article.sections))throw new Error('Invalid/duplicate article '+id+' in '+file);
   articles[id]={file,title:article.title||'',lead:article.lead};
  }
 }
 const serialized=JSON.stringify({version:1,articles},null,2);
 return '// Generated by scripts/build_theory_manifest.cjs. Do not edit.\nwindow.THEORY_MANIFEST = (() => {\n  const value = '+serialized+';\n  Object.values(value.articles).forEach(Object.freeze);\n  Object.freeze(value.articles);\n  return Object.freeze(value);\n})();\n';
}
module.exports={buildTheoryManifest};
if(require.main===module){
 const args=process.argv.slice(2),staticDir=path.resolve(args[0]||path.join(__dirname,'../static'));
 const result=buildTheoryManifest(staticDir);
 if(args[1]==='-')process.stdout.write(result);
 else {const target=path.resolve(args[1]||path.join(staticDir,'theory-manifest.js'));fs.writeFileSync(target,result);console.log('Generated '+target+' ('+Buffer.byteLength(result)+' bytes)');}
}
